-- Canonical stock column is stock_qty to match index.html and admin.html.

begin;

-- Migrate the earlier SQL column name when it exists, without silently overwriting stock data.
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='stock_quantity')
     and not exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='stock_qty') then
    alter table public.products rename column stock_quantity to stock_qty;
  elsif exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='stock_quantity')
     and exists (select 1 from information_schema.columns where table_schema='public' and table_name='products' and column_name='stock_qty') then
    raise exception 'Both stock_quantity and stock_qty exist. Reconcile their values manually before running this migration; no stock data was changed.';
  end if;
end $$;

alter table public.products
  add column if not exists subcategory text,
  add column if not exists selling_price numeric(12,2) not null default 0,
  add column if not exists mrp numeric(12,2) not null default 0,
  add column if not exists deal_scheme text,
  add column if not exists stock_qty integer not null default 0;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users(id) on delete cascade,
  store_name text not null,
  phone text not null,
  area text,
  status text not null default 'pending_whatsapp' check (status in ('pending_whatsapp','confirmed','processing','dispatched','completed','cancelled','expired')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 minutes'),
  stock_released boolean not null default false
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  category text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists orders_customer_created_idx on public.orders(customer_id, created_at desc);
create index if not exists orders_cleanup_idx on public.orders(created_at);
create index if not exists orders_expiry_idx on public.orders(status, expires_at);
create index if not exists order_items_order_idx on public.order_items(order_id);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Customers read own orders" on public.orders;
create policy "Customers read own orders" on public.orders for select to authenticated using (customer_id = auth.uid());

drop policy if exists "Customers read own order items" on public.order_items;
create policy "Customers read own order items" on public.order_items for select to authenticated using (
  exists (select 1 from public.orders o where o.id = order_items.order_id and o.customer_id = auth.uid())
);

drop policy if exists "MediSupply admin reads all orders" on public.orders;
create policy "MediSupply admin reads all orders" on public.orders for select to authenticated
using (auth.uid() = '8673d653-ee99-4fe1-a9ac-910edca92ad6'::uuid);

drop policy if exists "MediSupply admin reads all order items" on public.order_items;
create policy "MediSupply admin reads all order items" on public.order_items for select to authenticated
using (auth.uid() = '8673d653-ee99-4fe1-a9ac-910edca92ad6'::uuid);

-- Do not allow clients to directly insert/update orders or order items. Order creation happens through RPC.
revoke insert, update, delete on public.orders from anon, authenticated;
revoke insert, update, delete on public.order_items from anon, authenticated;
grant select on public.orders, public.order_items to authenticated;

create or replace function public.medisupply_create_order(
  p_items jsonb,
  p_store_name text,
  p_phone text,
  p_area text default null
) returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_customer uuid := auth.uid();
  v_order_id uuid;
  v_item jsonb;
  v_product_id uuid;
  v_qty integer;
  v_product public.products%rowtype;
begin
  if v_customer is null then raise exception 'Please login before placing an order.'; end if;
  if nullif(trim(p_store_name), '') is null then raise exception 'Medical store name is required.'; end if;
  if nullif(trim(p_phone), '') is null then raise exception 'Contact number is required.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Order must contain at least one product.'; end if;
  if jsonb_array_length(p_items) > 100 then raise exception 'Too many products in one order.'; end if;

  insert into public.orders(customer_id, store_name, phone, area)
  values (v_customer, trim(p_store_name), trim(p_phone), nullif(trim(coalesce(p_area,'')),''))
  returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    begin
      v_product_id := (v_item->>'product_id')::uuid;
      v_qty := (v_item->>'quantity')::integer;
    exception when others then raise exception 'Invalid product or quantity in order.';
    end;
    if v_qty is null or v_qty < 1 or v_qty > 10000 then raise exception 'Quantity must be between 1 and 10000.'; end if;

    -- Row-level lock + conditional decrement prevents overselling when two orders arrive together.
    update public.products
      set stock_qty = stock_qty - v_qty
      where id = v_product_id and is_active = true and stock_qty >= v_qty
      returning * into v_product;
    if not found then raise exception 'Product % is unavailable or has insufficient stock.', v_product_id; end if;

    insert into public.order_items(order_id, product_id, product_name, category, quantity, unit_price)
    values (v_order_id, v_product.id, v_product.name, v_product.category, v_qty, coalesce(v_product.selling_price,0));
  end loop;

  return v_order_id;
end;
$$;

revoke all on function public.medisupply_create_order(jsonb,text,text,text) from public;
grant execute on function public.medisupply_create_order(jsonb,text,text,text) to authenticated;


-- Admin-only order review. The UID matches the admin UID currently embedded in the uploaded admin.html.
create or replace function public.medisupply_admin_set_order_status(p_order_id uuid, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare r public.orders%rowtype;
begin
  if auth.uid() is distinct from '8673d653-ee99-4fe1-a9ac-910edca92ad6'::uuid then
    raise exception 'Not authorised as MediSupply admin.';
  end if;
  if p_status not in ('confirmed','cancelled','processing','dispatched','completed') then
    raise exception 'Invalid order status.';
  end if;
  select * into r from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found.'; end if;
  if r.status in ('cancelled','expired','completed') then raise exception 'This order can no longer be changed.'; end if;
  if p_status = 'cancelled' and r.stock_released = false then
    update public.products p set stock_qty = p.stock_qty + oi.quantity
      from public.order_items oi where oi.order_id = r.id and oi.product_id = p.id;
    update public.orders set status = 'cancelled', stock_released = true where id = r.id;
  else
    update public.orders set status = p_status where id = r.id;
  end if;
end;
$$;
revoke all on function public.medisupply_admin_set_order_status(uuid,text) from public, anon;
grant execute on function public.medisupply_admin_set_order_status(uuid,text) to authenticated;

-- Release reserved stock for pending WhatsApp orders that were never confirmed after 30 minutes,
-- and delete order records older than 15 days. Product catalogue/images are not deleted.
create or replace function public.medisupply_order_cleanup()
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare r record;
begin
  for r in
    select id from public.orders
    where status = 'pending_whatsapp' and expires_at <= now() and stock_released = false
    for update
  loop
    update public.products p
      set stock_qty = p.stock_qty + oi.quantity
      from public.order_items oi
      where oi.order_id = r.id and oi.product_id = p.id;
    update public.orders set status = 'expired', stock_released = true where id = r.id;
  end loop;

  delete from public.orders where created_at < now() - interval '15 days';
end;
$$;
revoke all on function public.medisupply_order_cleanup() from public, anon, authenticated;

commit;

